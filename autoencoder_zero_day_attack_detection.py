# ==========================================================
# AUTOENCODER-BASED ZERO-DAY ATTACK DETECTION
# Dataset: NSL-KDD (KDDTrain+.txt)
# ==========================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.metrics import classification_report
from sklearn.metrics import confusion_matrix
from sklearn.metrics import ConfusionMatrixDisplay
from sklearn.metrics import accuracy_score

from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, Dense
from tensorflow.keras.callbacks import EarlyStopping

# ==========================================================
# STEP 1: LOAD DATASET
# ==========================================================

DATASET_PATH = "/content/KDDTrain+.txt"

# NSL-KDD has no headers
df = pd.read_csv(DATASET_PATH, header=None)

print("Dataset Shape:", df.shape)
print(df.head())

# ==========================================================
# STEP 2: CONVERT LABELS
# ==========================================================

# Column 41 contains attack labels

df[41] = df[41].apply(
    lambda x: 0 if x == 'normal' else 1
)

print("\nClass Distribution:")
print(df[41].value_counts())

# ==========================================================
# STEP 3: ENCODE CATEGORICAL FEATURES
# ==========================================================

categorical_cols = df.select_dtypes(include='object').columns

print("\nEncoding categorical columns...")

for col in categorical_cols:
    encoder = LabelEncoder()
    df[col] = encoder.fit_transform(df[col])

# ==========================================================
# STEP 4: FEATURES AND TARGET
# ==========================================================

TARGET_COLUMN = 41

X = df.drop(TARGET_COLUMN, axis=1)
y = df[TARGET_COLUMN]

# ==========================================================
# STEP 5: FEATURE SCALING
# ==========================================================

scaler = StandardScaler()
X = scaler.fit_transform(X)

print("\nScaling completed")

# ==========================================================
# STEP 6: TRAIN TEST SPLIT
# ==========================================================

X_train_full, X_test, y_train_full, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Train only on normal traffic

X_train = X_train_full[y_train_full == 0]

print("\nTraining Samples:", X_train.shape)
print("Testing Samples:", X_test.shape)

# ==========================================================
# STEP 7: BUILD AUTOENCODER
# ==========================================================

input_dim = X_train.shape[1]

input_layer = Input(shape=(input_dim,))

# Encoder

encoded = Dense(64, activation='relu')(input_layer)
encoded = Dense(32, activation='relu')(encoded)
encoded = Dense(16, activation='relu')(encoded)

# Decoder

decoded = Dense(32, activation='relu')(encoded)
decoded = Dense(64, activation='relu')(decoded)
decoded = Dense(input_dim, activation='linear')(decoded)

autoencoder = Model(inputs=input_layer,
                    outputs=decoded)

autoencoder.compile(
    optimizer='adam',
    loss='mse'
)

autoencoder.summary()

# ==========================================================
# STEP 8: TRAIN MODEL
# ==========================================================

early_stop = EarlyStopping(
    monitor='val_loss',
    patience=5,
    restore_best_weights=True
)

history = autoencoder.fit(
    X_train,
    X_train,
    epochs=50,
    batch_size=64,
    validation_split=0.2,
    callbacks=[early_stop],
    shuffle=True
)

# ==========================================================
# STEP 9: LOSS CURVE
# ==========================================================

plt.figure(figsize=(8,5))

plt.plot(history.history['loss'],
         label='Training Loss')

plt.plot(history.history['val_loss'],
         label='Validation Loss')

plt.title('Loss Curve')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.show()

# ==========================================================
# STEP 10: RECONSTRUCTION ERROR
# ==========================================================

reconstructed = autoencoder.predict(X_test)

mse = np.mean(
    np.square(X_test - reconstructed),
    axis=1
)

print("\nSample Errors:")
print(mse[:10])

# ==========================================================
# STEP 11: THRESHOLD
# ==========================================================

threshold = np.percentile(mse, 95)

print("\nThreshold:", threshold)

# ==========================================================
# STEP 12: PREDICTIONS
# ==========================================================

y_pred = (mse > threshold).astype(int)

# ==========================================================
# STEP 13: EVALUATION
# ==========================================================

print("\nClassification Report\n")

print(
    classification_report(
        y_test,
        y_pred
    )
)

accuracy = accuracy_score(y_test, y_pred)

print("\nAccuracy:",
      round(accuracy*100,2),
      "%")

# ==========================================================
# STEP 14: CONFUSION MATRIX
# ==========================================================

cm = confusion_matrix(y_test, y_pred)

disp = ConfusionMatrixDisplay(
    confusion_matrix=cm
)

disp.plot()

plt.title("Confusion Matrix")
plt.show()

# ==========================================================
# STEP 15: ERROR DISTRIBUTION
# ==========================================================

plt.figure(figsize=(8,5))

plt.hist(mse,
         bins=50)

plt.axvline(
    threshold,
    color='red',
    linestyle='--',
    label='Threshold'
)

plt.xlabel('Reconstruction Error')
plt.ylabel('Count')
plt.title('Reconstruction Error Distribution')

plt.legend()
plt.show()

# ==========================================================
# STEP 16: SAVE MODEL
# ==========================================================

autoencoder.save(
    "/content/autoencoder_zero_day_model.h5"
)

print("\nModel Saved Successfully!")